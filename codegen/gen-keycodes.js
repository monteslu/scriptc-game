  ESCAPE: "Escape",
  BACKSPACE: "Backspace",
  TAB: "Tab",
  SPACE: "Space",
  MINUS: "Minus",
  EQUALS: "Equal",
  LEFTBRACKET: "BracketLeft",
  RIGHTBRACKET: "BracketRight",
  BACKSLASH: "Backslash",
  NONUSHASH: "Backslash",
  SEMICOLON: "Semicolon",
  APOSTROPHE: "Quote",
  GRAVE: "Backquote",
  COMMA: "Comma",
  PERIOD: "Period",
  SLASH: "Slash",
  CAPSLOCK: "CapsLock",
  PRINTSCREEN: "PrintScreen",
  SCROLLLOCK: "ScrollLock",
  PAUSE: "Pause",
  INSERT: "Insert",
  HOME: "Home",
  PAGEUP: "PageUp",
  DELETE: "Delete",
  END: "End",
  PAGEDOWN: "PageDown",
  RIGHT: "ArrowRight",
  LEFT: "ArrowLeft",
  DOWN: "ArrowDown",
  UP: "ArrowUp",
  NUMLOCKCLEAR: "NumLock",
  KP_DIVIDE: "NumpadDivide",
  KP_MULTIPLY: "NumpadMultiply",
  KP_MINUS: "NumpadSubtract",
  KP_PLUS: "NumpadAdd",
  KP_ENTER: "NumpadEnter",
  KP_PERIOD: "NumpadDecimal",
  KP_EQUALS: "NumpadEqual",
  KP_COMMA: "NumpadComma",
  NONUSBACKSLASH: "IntlBackslash",
  APPLICATION: "ContextMenu",
  LCTRL: "ControlLeft",
  LSHIFT: "ShiftLeft",
  LALT: "AltLeft",
  LGUI: "MetaLeft",
  RCTRL: "ControlRight",
  RSHIFT: "ShiftRight",
  RALT: "AltRight",
  RGUI: "MetaRight",
  MENU: "ContextMenu",
  INTERNATIONAL1: "IntlRo",
  INTERNATIONAL3: "IntlYen",
  LANG1: "Lang1",
  LANG2: "Lang2",
